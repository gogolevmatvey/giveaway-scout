// Offline preparation only: never creates keys, publishes, builds or installs.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { isDeepStrictEqual, parseArgs } from 'node:util';
import { pathToFileURL } from 'node:url';

export const repository = 'gogolevmatvey/giveaway-scout';
export const endpoint = `https://github.com/${repository}/releases/latest/download/latest.json`;

function base64(value) {
  if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(value) || !value) {
    throw new Error('Expected a Tauri base64 public key, not a private key or a filename.');
  }
  const bytes = Buffer.from(value, 'base64');
  if (bytes.toString('base64') !== value) throw new Error('Noncanonical public key.');
  return bytes;
}

export function publicKey(value) {
  if (typeof value !== 'string' || value.length > 4096) throw new Error('Invalid public key size.');
  const key = value.trim();
  const lines = base64(key).toString('utf8').trim().split(/\r?\n/);
  if (lines.length !== 2 || !/^untrusted comment: [\x20-\x7e]*$/.test(lines[0])) {
    throw new Error('Expected the public .pub file generated by Tauri signer.');
  }
  const bytes = base64(lines[1]);
  if (bytes.length !== 42 || bytes.subarray(0, 2).toString('ascii') !== 'Ed') {
    throw new Error('Invalid Minisign public key; private keys are not accepted.');
  }
  return key;
}

export function createConfig(key) {
  return {
    bundle: { targets: ['nsis'], createUpdaterArtifacts: true },
    plugins: { updater: {
      endpoints: [endpoint], pubkey: publicKey(key),
      requireSignedVersion: true, allowDowngrades: false,
      windows: { installMode: 'passive' },
    } },
  };
}

export function verifyConfig(config) {
  const expected = createConfig(config?.plugins?.updater?.pubkey);
  if (!isDeepStrictEqual(config, expected)) {
    throw new Error('Unexpected release configuration. Only the agreed GitHub channel, NSIS and strict signatures are allowed.');
  }
  return createHash('sha256').update(expected.plugins.updater.pubkey).digest('hex');
}

export function main(args) {
  const {values} = parseArgs({args, options: {
    'public-key': {type: 'string'}, output: {type: 'string'}, verify: {type: 'string'},
  }, allowPositionals: false});
  if (values.verify) {
    if (values['public-key'] || values.output) throw new Error('--verify cannot be combined with generation.');
    if (fs.statSync(values.verify).size > 16_384) throw new Error('Configuration is too large.');
    const file = fs.readFileSync(values.verify, 'utf8');
    let config;
    try { config = JSON.parse(file); }
    catch { throw new Error('Invalid updater configuration JSON.'); }
    const fingerprint = verifyConfig(config);
    console.log(`GitHub updater configuration verified offline. Public-key SHA-256: ${fingerprint}`);
    return;
  }
  if (!values['public-key'] || !values.output) {
    throw new Error('Use --public-key <existing .pub> --output <new config.json>, or --verify <config.json>.');
  }
  // Size-limit BEFORE reading, to avoid accidentally consuming an unrelated file.
  if (fs.statSync(values['public-key']).size > 4096) throw new Error('Public key file is too large.');
  const config = createConfig(fs.readFileSync(values['public-key'], 'utf8'));
  const fingerprint = verifyConfig(config);
  fs.writeFileSync(values.output, JSON.stringify(config, null, 2) + '\n', {flag: 'wx', mode: 0o600});
  console.log(`Created release overlay for ${repository}. Public-key SHA-256: ${fingerprint}`);
  console.log('No key was created and no network request, publication, build or installation was performed.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { main(process.argv.slice(2)); }
  catch (error) {
    // Do not echo supplied files, JSON or key material on failure.
    console.error(error instanceof Error ? error.message : 'Updater configuration failed.');
    process.exitCode = 1;
  }
}
